// Generate import.sql lengkap (skema + constraint + index + function + data)
// dari DB Supabase lama (via Management API) + hasil backup JSON.
//
// Output dipakai untuk membuat project Supabase PostgreSQL baru GRATIS.
// Jalankan: node scripts/generate-import-sql.mjs

import fs from "fs";
import path from "path";
import { fileURLToPath } from "url";
import dotenv from "dotenv";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
dotenv.config({ path: path.join(__dirname, "..", ".env.local") });

const TOKEN = process.env.SUPABASE_ACCESS_TOKEN;
const REF =
  process.env.SUPABASE_PROJECT_REF ||
  (process.env.NEXT_PUBLIC_SUPABASE_URL || "").match(/https:\/\/([a-z0-9]+)\.supabase\.co/)?.[1];

const INSERT_ORDER = [
  "clients",
  "cards",
  "menu_categories",
  "menu_items",
  "client_users",
  "company_users",
  "table_qrs",
  "card_feedback",
  "card_audit_log",
];

async function q(sql) {
  const res = await fetch(`https://api.supabase.com/v1/projects/${REF}/database/query`, {
    method: "POST",
    headers: { Authorization: `Bearer ${TOKEN}`, "Content-Type": "application/json" },
    body: JSON.stringify({ query: sql, read_only: true }),
  });
  const t = await res.text();
  if (!res.ok) throw new Error(`HTTP ${res.status}: ${t.slice(0, 400)}`);
  const j = JSON.parse(t);
  return Array.isArray(j) ? j : j.result || j.data || j.rows;
}

const qIdent = (s) => `"${String(s).replace(/"/g, '""')}"`;
const qStr = (s) => `'${String(s).replace(/'/g, "''")}'`;

function latestBackupDir() {
  const base = path.join(__dirname, "..", "backups");
  const dirs = fs
    .readdirSync(base, { withFileTypes: true })
    .filter((d) => d.isDirectory())
    .map((d) => d.name)
    .sort();
  if (!dirs.length) throw new Error("Tidak ada folder backups/*. Jalankan backup dulu.");
  return path.join(base, dirs[dirs.length - 1]);
}

function sqlValue(v) {
  if (v === null || v === undefined) return "NULL";
  if (typeof v === "boolean") return v ? "true" : "false";
  if (typeof v === "number") return Number.isFinite(v) ? String(v) : "NULL";
  if (typeof v === "object") return `${qStr(JSON.stringify(v))}::jsonb`;
  return qStr(v);
}

async function main() {
  if (!TOKEN || !REF) throw new Error("Butuh SUPABASE_ACCESS_TOKEN + project ref.");
  const backupDir = latestBackupDir();
  console.log("Backup:", backupDir);

  const cols = await q(`
    select c.relname as table_name, a.attnum, a.attname as column_name,
           format_type(a.atttypid, a.atttypmod) as coltype,
           a.attnotnull as notnull, a.attidentity as identity,
           pg_get_expr(d.adbin, d.adrelid) as default_expr
    from pg_attribute a
    join pg_class c on c.oid = a.attrelid
    join pg_namespace n on n.oid = c.relnamespace
    left join pg_attrdef d on d.adrelid = a.attrelid and d.adnum = a.attnum
    where n.nspname = 'public' and c.relkind = 'r'
      and a.attnum > 0 and not a.attisdropped
    order by c.relname, a.attnum
  `);
  const constraints = await q(`
    select conrelid::regclass::text as tbl, conname, pg_get_constraintdef(oid) as def
    from pg_constraint where connamespace = 'public'::regnamespace
    order by tbl, conname
  `);
  const indexes = await q(`
    select tablename, indexdef from pg_indexes
    where schemaname = 'public' and indexdef like 'CREATE INDEX%'
    order by tablename, indexname
  `);
  const functions = await q(`
    select p.proname, pg_get_functiondef(p.oid) as def
    from pg_proc p join pg_namespace n on n.oid = p.pronamespace
    where n.nspname = 'public' order by p.proname
  `);

  const tables = {};
  for (const c of cols) (tables[c.table_name] ??= []).push(c);

  let sql = "";
  sql += "-- ============================================================\n";
  sql += "-- Import Ratey: skema + data dari project lama\n";
  sql += "-- Dibuat otomatis. Jalankan di SQL Editor project Supabase BARU.\n";
  sql += "-- ============================================================\n\n";
  sql += "begin;\n\n";

  // 1. Tables
  sql += "-- === TABLES ===\n";
  for (const [name, list] of Object.entries(tables)) {
    const parts = list.map((c) => {
      let line = `${qIdent(c.column_name)} ${c.coltype}`;
      if (c.identity === "a") line += " generated always as identity";
      else if (c.identity === "d") line += " generated by default as identity";
      else if (c.default_expr && /nextval\(/i.test(c.default_expr)) {
        // serial/bigserial: sequence dibuat otomatis, default lama diabaikan
        if (/^bigint$/i.test(c.coltype)) line = `${qIdent(c.column_name)} bigserial`;
        else if (/^integer$/i.test(c.coltype)) line = `${qIdent(c.column_name)} serial`;
        else line += ` default ${c.default_expr}`;
      } else if (c.default_expr) {
        line += ` default ${c.default_expr}`;
      }
      if (c.notnull && c.identity === "" && !/serial$/i.test(line)) line += " not null";
      return line;
    });
    sql += `create table if not exists public.${qIdent(name)} (\n  ${parts.join(",\n  ")}\n);\n`;
  }

  // 2. Constraints — PK/UNIQUE dulu, baru FK/CHECK (biar referensi sudah valid)
  sql += "\n-- === CONSTRAINTS ===\n";
  const first = constraints.filter((c) => /PRIMARY KEY|UNIQUE/i.test(c.def));
  const rest = constraints.filter((c) => !/PRIMARY KEY|UNIQUE/i.test(c.def));
  for (const c of [...first, ...rest]) {
    sql += `alter table public.${qIdent(c.tbl)} add constraint ${qIdent(c.conname)} ${c.def};\n`;
  }

  // 3. Indexes (yang bukan milik constraint)
  sql += "\n-- === INDEXES ===\n";
  for (const i of indexes) sql += `${i.indexdef};\n`;

  // 3b. RLS (service_role tetap bypass; anon/authenticated tidak bisa akses langsung)
  sql += "\n-- === ROW LEVEL SECURITY ===\n";
  for (const name of Object.keys(tables)) sql += `alter table public.${qIdent(name)} enable row level security;\n`;

  // 4. Functions
  sql += "\n-- === FUNCTIONS ===\n";
  for (const f of functions) sql += `${f.def};\n`;

  // 5. Data
  sql += "\n-- === DATA ===\n";
  const counts = {};
  for (const name of INSERT_ORDER) {
    const file = path.join(backupDir, `${name}.json`);
    if (!fs.existsSync(file)) continue;
    const rows = JSON.parse(fs.readFileSync(file, "utf8"));
    counts[name] = rows.length;
    if (!rows.length) continue;
    const columns = Object.keys(rows[0]);
    const colList = columns.map(qIdent).join(", ");
    for (const row of rows) {
      const vals = columns.map((c) => sqlValue(row[c])).join(", ");
      sql += `insert into public.${qIdent(name)} (${colList}) values (${vals});\n`;
    }
    sql += "\n";
  }

  // 6. Reset sequences
  sql += "-- === RESET SEQUENCES ===\n";
  for (const name of Object.keys(tables)) {
    const hasId = tables[name].some((c) => c.column_name === "id");
    if (!hasId) continue;
    sql += `select setval(pg_get_serial_sequence('public.${name}', 'id'), coalesce((select max(id) from public.${name}), 1));\n`;
  }

  sql += "\n-- === GRANTS (service_role dipakai server-side) ===\n";
  sql += "grant usage on schema public to service_role, anon, authenticated;\n";
  sql += "grant all privileges on all tables in schema public to service_role;\n";
  sql += "grant all privileges on all sequences in schema public to service_role;\n";

  sql += "\ncommit;\n";

  const out = path.join(backupDir, "import.sql");
  fs.writeFileSync(out, sql);
  console.log("Ditulis:", out, `(${(sql.length / 1024).toFixed(1)} KB)`);
  console.log("Baris data:", JSON.stringify(counts));
}

main().catch((e) => {
  console.error("\n✗", e instanceof Error ? e.message : e);
  process.exit(1);
});
